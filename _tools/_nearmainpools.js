// Bakes functions/lxapi/_nearmainpools.js: each curated token's MAIN Rhea pool (the one with the most liquidity in
// assets/tokenpools/<token>.json, which _nearpoolcounts.js bakes).
//
// WHY (RAZA 2026-11-14, /trade/near page 2: "most of the assets arent carrying 24h Change value ... infact i believe
// that the values are incorrect because its just showing 0"). DexScreener does not index 16 of the curated tokens at
// all (NearX, RIBBIT, NEARAI, ...), so /lxapi/nearmarket printed their volume, trades and liquidity as 0 -- a source
// that has never heard of a token, presented as a token nobody trades. The edge now reads such a token's main pool
// from the chain for its liquidity; this file is how it knows which pool that is.
//
// Run: node _tools/_nearmainpools.js   (after _nearpoolcounts.js, and whenever the curated list changes)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'functions/lxapi/_nearcurated.js'), 'utf8');
const m = src.match(/export const CURATED = (\[[\s\S]*?\]);\s*$/m);
if (!m) throw new Error('CURATED not found in _nearcurated.js');
const CURATED = JSON.parse(m[1]);

// A token with no pool file (its liquidity is on Rhea's concentrated-liquidity contract, dclv2.ref-labs.near, which
// the pool files do not cover -- NEARAGENTS, SPUD, NEARSIGHT) is looked up once on GeckoTerminal, whose pool address
// for such a pool is "refv2-<token_x>:<token_y>:<fee>"; the DCL contract names the same pool "<x>|<y>|<fee>".
// Answers are cached in _tools/nearmainpools.cache.json, so a re-run asks only about tokens it has never seen
// (GeckoTerminal is shared with RAZA's own browsing on this IP: paced, never hammered).
const CACHE = path.join(__dirname, 'nearmainpools.cache.json');
const cache = fs.existsSync(CACHE) ? JSON.parse(fs.readFileSync(CACHE, 'utf8')) : {};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function geckoPool(id) {
  if (Object.prototype.hasOwnProperty.call(cache, id)) return cache[id];
  await sleep(4500);
  const r = await fetch('https://api.geckoterminal.com/api/v2/networks/near/tokens/' + encodeURIComponent(id) + '/pools?page=1',
    { headers: { accept: 'application/json' } });
  if (!r.ok) return undefined;                      // not cached: asked again next run
  const j = await r.json();
  let got = null;
  // GeckoTerminal lists a token's pools by liquidity, both kinds: "refv1-<id>" classic, "refv2-x:y:fee" concentrated.
  for (const p of (j.data || [])) {
    const a = String((p.attributes || {}).address || '');
    let m2;
    if (!(+(p.attributes || {}).reserve_in_usd > 0)) continue;
    if ((m2 = a.match(/^refv1-(\d{1,9})$/))) { got = Number(m2[1]); break; }
    if ((m2 = a.match(/^refv2-([a-z0-9._-]+):([a-z0-9._-]+):(\d{1,6})$/))) { got = m2[1] + '|' + m2[2] + '|' + m2[3]; break; }
  }
  cache[id] = got;
  return got;
}

(async () => {
  const out = {};
  const missing = [];
  for (const c of CURATED) {
    if (c.i === 'wrap.near') continue;
    if (c.pool != null) { out[c.i] = Number(c.pool); continue; }   // our own pool (LUMOS 9001)
    // GeckoTerminal FIRST: the pool files list classic pools only, so for DRAGON, CLAW and NOMO they named a $1
    // classic pool while the token's real market is a $5-10K concentrated one (measured 2026-11-14).
    const g0 = await geckoPool(c.i);
    if (g0 != null) { out[c.i] = g0; continue; }
    const f = path.join(ROOT, 'assets/tokenpools', c.i + '.json');
    let best = null;
    if (fs.existsSync(f)) {
      for (const e of JSON.parse(fs.readFileSync(f, 'utf8'))) {
        if (!Array.isArray(e) || !/^\d{1,9}$/.test(String(e[0]))) continue;
        if (!best || (+e[1] || 0) > (+best[1] || 0)) best = e;
      }
    }
    if (best) out[c.i] = Number(best[0]); else missing.push(c.i);
  }
  fs.writeFileSync(CACHE, JSON.stringify(cache, null, 1));
  const body = '// GENERATED by _tools/_nearmainpools.js -- do not edit. Each curated token\'s main Rhea pool:\n'
    + '// a number is a classic pool on v2.ref-finance.near, "x|y|fee" a concentrated one on dclv2.ref-labs.near.\n'
    + 'export const MAINPOOL = ' + JSON.stringify(out) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'functions/lxapi/_nearmainpools.js'), body);
  // The pool indexer's hourly price job (workers/near-pool-indexer, snapPoolPrices) prices each token off this same
  // pool, so it needs the pool and the token's decimals. A concentrated pool not against wNEAR cannot price in NEAR
  // and is left out; a classic pool's pairing is checked when it is read.
  const px = {};
  for (const c of CURATED) {
    const p = out[c.i];
    if (p == null || c.d == null) continue;
    if (typeof p === 'string' && p.split('|').indexOf('wrap.near') < 0) continue;
    px[c.i] = [p, c.d];
  }
  fs.writeFileSync(path.join(ROOT, 'workers/near-pool-indexer/src/poolpx.js'),
    '// GENERATED by _tools/_nearmainpools.js -- do not edit. token -> [main pool, decimals]: a number is a classic pool\n'
    + '// on v2.ref-finance.near, "x|y|fee" a concentrated one on dclv2.ref-labs.near. Read by snapPoolPrices.\n'
    + 'export const POOLPX = ' + JSON.stringify(px) + ';\n');
  console.log('indexer pool prices: ' + Object.keys(px).length + ' token(s)');
  const dcl = Object.values(out).filter((v) => typeof v === 'string').length;
  console.log('main pools: ' + Object.keys(out).length + ' token(s), ' + dcl + ' concentrated'
    + (missing.length ? '; no pool found for ' + missing.join(', ') : ''));
})().catch((e) => { console.error(e); process.exit(1); });
