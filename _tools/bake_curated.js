// Bake _tools/nearcurated.generated.json into a module the NEAR Functions import:
// functions/lxapi/_nearcurated.js. Part of `npm run build`.
//
// The JSON stays the source of truth (it is what _nearcurate.js writes and what a person reviews);
// this only makes it importable at the edge, where a Function cannot read a file. Fails the build on
// an empty or unreadable list rather than shipping a market table with no rows.
const fs = require('fs');
const path = require('path');
const SRC = path.join(__dirname, 'nearcurated.generated.json');
const OUT = path.join(__dirname, '..', 'functions', 'lxapi', '_nearcurated.js');
let j;
try { j = JSON.parse(fs.readFileSync(SRC, 'utf8')); } catch (e) { console.error('bake_curated: ' + e.message); process.exit(1); }
const tokens = (j && j.tokens) || [];
// A token whose own metadata has no usable icon gets one from nearlogos.fallback.json (CoinGecko or
// DexScreener's image for that token); a logo the token publishes is never replaced.
const FALLBACK = JSON.parse(fs.readFileSync(path.join(__dirname, 'nearlogos.fallback.json'), 'utf8')).logos || {};
let filled = 0;
for (const t of tokens) if (!t.logo && FALLBACK[t.i]) { t.logo = FALLBACK[t.i]; filled++; }
// The issuer's website and X profile (_nearlinks.js writes them; absent until it has run once).
let LINKS = {};
try { LINKS = JSON.parse(fs.readFileSync(path.join(__dirname, 'nearlinks.generated.json'), 'utf8')).links || {}; } catch (e) {}
let linked = 0;
for (const t of tokens) {
  const l = LINKS[t.i];
  if (!l) continue;
  if (l.w) t.w = l.w;
  if (l.x) t.x = l.x;
  linked++;
}
if (!tokens.length) { console.error('bake_curated: the curated list is empty — run node _tools/_nearcurate.js'); process.exit(1); }
fs.writeFileSync(OUT, '// GENERATED by _tools/bake_curated.js from _tools/nearcurated.generated.json — do not edit.\n'
  + '// ' + tokens.length + ' token(s), generated ' + j.generated + '.\n'
  + 'export const CURATED = ' + JSON.stringify(tokens) + ';\n', 'utf8');
console.log('bake_curated: ' + tokens.length + ' token(s), ' + filled + ' fallback logo(s), ' + linked + ' with links -> functions/lxapi/_nearcurated.js');
