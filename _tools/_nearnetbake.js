// Bake NEAR's account and token totals for the Dashboard's Network Stats: functions/lxapi/_nearnetbaked.js.
// Part of `npm run build`.
//
// RAZA 2026-11-05: "Why are network stats taking so long to load". NearBlocks refuses Cloudflare's IPs with 429, Pages
// Functions and Workers alike, so neither can read these two figures at all (the worker tried every two minutes for a
// day). They answer from a normal connection, and both move slowly, so they are read at build time. Pools stay live
// through the pool indexer (workers/near-pool-indexer netJob).
//
// A failed read keeps the last baked figures and does not fail the build; nearstats.js marks them stale by age.
const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, '..', 'functions', 'lxapi', '_nearnetbaked.js');
const UA = { headers: { accept: 'application/json', 'user-agent': 'LumosCore/1.0 (+https://lumoscore.com)' } };

function sumField(t, key) {
  const A = '"' + key + '":"';
  let n = 0, i = 0, rows = 0;
  for (;;) {
    i = t.indexOf(A, i);
    if (i < 0) break;
    i += A.length;
    const v = parseInt(t.slice(i, t.indexOf('"', i)), 10);
    if (isFinite(v)) { n += v; rows++; }
  }
  return { n, rows };
}

(async () => {
  const [cr, fr] = await Promise.all([fetch('https://api.nearblocks.io/v1/charts', UA), fetch('https://api.nearblocks.io/v1/fts/count', UA)]);
  if (!cr.ok || !fr.ok) throw new Error('nearblocks ' + cr.status + ' / ' + fr.status);
  const t = await cr.text(), f = await fr.json();
  const made = sumField(t, 'new_accounts'), gone = sumField(t, 'deleted_accounts');
  // A history that stops short is a truncated body or a changed shape, not a small network.
  if (made.rows < 2000 || !(made.n > 1e8)) throw new Error('charts: ' + made.rows + ' rows');
  const assets = Number(((f.tokens || [])[0] || {}).count);
  if (!(assets > 0)) throw new Error('fts/count: no count');
  const iA = t.lastIndexOf('"active_accounts":"'), iD = t.lastIndexOf('"date":"');
  const active = iA < 0 ? null : parseInt(t.slice(iA + 19, t.indexOf('"', iA + 19)), 10);
  const out = { accounts: made.n - gone.n, assets, active: isFinite(active) ? active : null, day: iD < 0 ? null : t.slice(iD + 8, iD + 18), at: Date.now() };
  fs.writeFileSync(OUT, '// GENERATED by _tools/_nearnetbake.js -- do not edit.\nexport const NET = ' + JSON.stringify(out) + ';\n', 'utf8');
  console.log('nearnetbake: ' + out.accounts + ' accounts, ' + out.assets + ' tokens, as of ' + out.day);
})().catch((e) => { console.error('nearnetbake: kept the last figures (' + e.message + ')'); });
