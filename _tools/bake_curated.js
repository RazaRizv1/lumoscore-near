// Bake _tools/nearcurated.generated.json into a module the NEAR Functions import:
// functions/lxapi/_nearcurated.js. Part of `npm run build`.
//
// The JSON stays the source of truth (it is what _nearcurate.js writes and what a person reviews);
// this only makes it importable at the edge, where a Function cannot read a file. Fails the build on
// an empty or unreadable list rather than shipping a market table with no rows.
const fs = require('fs');
const path = require('path');
const SRC = path.join(__dirname, 'nearcurated.generated.json');
const OUT = path.join(__dirname, '..', 'functions', 'lxapi', '_nearcurated.js');
let j;
try { j = JSON.parse(fs.readFileSync(SRC, 'utf8')); } catch (e) { console.error('bake_curated: ' + e.message); process.exit(1); }
const tokens = (j && j.tokens) || [];
// A token whose own metadata has no usable icon gets one from nearlogos.fallback.json (CoinGecko or
// DexScreener's image for that token); a logo the token publishes is never replaced.
// A published logo whose url is listed under `dead` (its host is gone) counts as no logo.
const FB = JSON.parse(fs.readFileSync(path.join(__dirname, 'nearlogos.fallback.json'), 'utf8'));
const FALLBACK = FB.logos || {}, DEAD = FB.dead || {};
let filled = 0;
for (const t of tokens) if ((!t.logo || DEAD[t.logo]) && FALLBACK[t.i]) { t.logo = FALLBACK[t.i]; filled++; }
// The issuer's website and X profile (_nearlinks.js writes them; absent until it has run once).
let LINKS = {};
try { LINKS = JSON.parse(fs.readFileSync(path.join(__dirname, 'nearlinks.generated.json'), 'utf8')).links || {}; } catch (e) {}
// Each token's holder count as last read (_nearholdercounts.js), the endpoint's fallback when NearBlocks is busy.
let HC = {};
try { HC = JSON.parse(fs.readFileSync(path.join(__dirname, 'nearholdercounts.generated.json'), 'utf8')).counts || {}; } catch (e) {}
let counted = 0;
for (const t of tokens) { const c = HC[t.i]; if (c && c.n > 0) { t.hc = c.n; t.hca = c.at; counted++; } }
// Each token's pool count on Rhea (_nearpoolcounts.js): every pool holding it, and the ones with liquidity.
let PC = {};
try { PC = JSON.parse(fs.readFileSync(path.join(__dirname, 'nearpoolcounts.generated.json'), 'utf8')).counts || {}; } catch (e) {}
let pooled = 0;
for (const t of tokens) { const c = PC[t.i]; if (c && c.n > 0) { t.pc = c.n; t.pcl = c.live; pooled++; } }
let linked = 0;
for (const t of tokens) {
  const l = LINKS[t.i];
  if (!l) continue;
  if (l.w) t.w = l.w;
  if (l.x) t.x = l.x;
  linked++;
}
if (!tokens.length) { console.error('bake_curated: the curated list is empty — run node _tools/_nearcurate.js'); process.exit(1); }
// LUMOS IS LUMOSCORE'S OWN TOKEN (RAZA 2026-11-04: its new pool read "Not curated by LumosCore"). The list above is
// drawn from the market ($25K+ liquidity), which a token minted the same day cannot pass; LumosCore vouches for its
// own token, as Stellar lists its LUMOS. Added whenever _tools/near-lumos.js names it.
const { NEAR_LUMOS, NEAR_LUMOS_POOL } = require(path.join(__dirname, 'near-lumos.js'));
if (NEAR_LUMOS && !tokens.some((t) => t.i === NEAR_LUMOS)) {
  tokens.push({ i: NEAR_LUMOS, s: 'LUMOS', n: 'LumosCore', d: 18, logo: '/assets/tokens/lumos.png', st: 0, v: 0,
    w: 'https://lumoscore.com', x: 'https://x.com/LumosCore' });
  console.log('bake_curated: LUMOS (' + NEAR_LUMOS + ') added as LumosCore\'s own token');
}
// Its own pool, read from the chain while Rhea's indexer does not carry it (functions/lxapi/_nearownpools.js).
const lumosRow = NEAR_LUMOS && tokens.find((t) => t.i === NEAR_LUMOS);
if (lumosRow && NEAR_LUMOS_POOL != null) lumosRow.pool = NEAR_LUMOS_POOL;
fs.writeFileSync(OUT, '// GENERATED by _tools/bake_curated.js from _tools/nearcurated.generated.json — do not edit.\n'
  + '// ' + tokens.length + ' token(s), generated ' + j.generated + '.\n'
  + 'export const CURATED = ' + JSON.stringify(tokens) + ';\n', 'utf8');
console.log('bake_curated: ' + tokens.length + ' token(s), ' + filled + ' fallback logo(s), ' + linked + ' with links, ' + counted + ' with holder counts, ' + pooled + ' with pool counts -> functions/lxapi/_nearcurated.js');
